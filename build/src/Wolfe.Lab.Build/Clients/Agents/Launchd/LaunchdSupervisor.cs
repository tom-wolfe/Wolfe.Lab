using System.Globalization;
using System.Xml.Linq;
using Microsoft.Extensions.Options;
using Polly.Registry;
using Wolfe.Lab.Build.Clients.Resilience;

namespace Wolfe.Lab.Build.Clients.Agents.Launchd;

/// <summary>
/// launchd, through launchctl. Units are written to the user's LaunchAgents directory and
/// bootstrapped into the GUI domain.
/// </summary>
internal sealed class LaunchdSupervisor(AgentDirectory agents, ICommandRunner commands, IWorkflowLog log, ResiliencePipelineProvider<string> pipelines, IOptions<LaunchdOptions> options) : IServiceSupervisor
{
    private UserDomain? _domain;

    /// <inheritdoc />
    public AgentUnit Render(AgentDefinition agent) => new($"{agent.Label.Value}.plist", Plist.Write(Unit(agent)));

    /// <summary>
    /// The agent as a property list, built rather than templated: the XML writer escapes what
    /// it is handed, so no value can break out of its element.
    /// </summary>
    /// <remarks>
    /// The comment carries the executable's and the artifacts' stamps: the render is compared as
    /// text, so a new binary or new artifacts restart the agent without anyone editing it.
    /// </remarks>
    internal static XDocument Unit(AgentDefinition agent)
    {
        var entries = new List<XElement>();
        void Entry(string key, XElement value) => entries.AddRange(new XElement("key", key), value);

        Entry("Label", Plist.String(agent.Label.Value));
        Entry("ProgramArguments", new XElement("array", agent.Arguments.Prepend(agent.Program.Value).Select(Plist.String)));
        if (agent.WorkingDirectory is { } workingDirectory)
        {
            Entry("WorkingDirectory", Plist.String(workingDirectory.Value));
        }

        if (agent.Environment.Count > 0)
        {
            // Ordered, because the render is compared as text: a dictionary that came out of
            // JSON in a different order must not read as a changed agent.
            Entry("EnvironmentVariables", new XElement("dict", agent.Environment
                .OrderBy(variable => variable.Key, StringComparer.Ordinal)
                .SelectMany(variable => new[] { new XElement("key", variable.Key), Plist.String(variable.Value) })));
        }

        Entry("RunAtLoad", Plist.Boolean(true));
        Entry("KeepAlive", Plist.Boolean(agent.KeepAlive));
        if (agent.ExitTimeout is { } timeout)
        {
            Entry("ExitTimeOut", new XElement("integer", timeout));
        }

        if (agent.Log is { } log)
        {
            Entry("StandardOutPath", Plist.String(log.Value));
            Entry("StandardErrorPath", Plist.String(log.Value));
        }

        var provenance = new List<string>
        {
            " Generated by `lab deploy` — edits here are overwritten.",
            $" program: {agent.Program.Value}",
            $" stamped: {Stamp(agent.ProgramStamp)}"
        };
        if (agent.ArtifactStamp is { } artifacts)
        {
            provenance.Add($" artifacts: {Stamp(artifacts)}");
        }

        return Plist.Document(string.Join('\n', provenance), new XElement("dict", entries));
    }

    private static string Stamp(DateTimeOffset stamp) => stamp.UtcDateTime.ToString("O", CultureInfo.InvariantCulture);

    /// <inheritdoc />
    public async Task<AgentOutcome> Plan(AgentDefinition agent, CancellationToken ct = default)
    {
        var unit = Render(agent);
        var installed = await agents.Directory.GetFile(unit.FileName).ReadAllTextIfExists(ct);
        if (!await IsLoaded(agent.Label, ct))
        {
            return AgentOutcome.Installed;
        }

        return installed == unit.Content ? AgentOutcome.Unchanged : AgentOutcome.Restarted;
    }

    /// <inheritdoc />
    public async Task<AgentOutcome> Converge(AgentDefinition agent, CancellationToken ct = default)
    {
        var unit = Render(agent);
        var file = agents.Directory.GetFile(unit.FileName);
        var installed = await file.ReadAllTextIfExists(ct);
        var loaded = await IsLoaded(agent.Label, ct);

        if (installed == unit.Content && loaded)
        {
            return AgentOutcome.Unchanged;
        }

        if (installed != unit.Content)
        {
            // Atomic: the supervisor may read the unit at any moment, and must never see half of it.
            await file.WriteAllText(unit.Content, mode: UnitPermissions.Owner, cancellationToken: ct);
        }

        if (!loaded)
        {
            await Bootstrap(file, ct);
            return AgentOutcome.Installed;
        }

        await Restart(agent, file, ct);
        return AgentOutcome.Restarted;
    }

    /// <inheritdoc />
    public async Task<bool> IsInstalled(string unit, CancellationToken ct = default) =>
        agents.Directory.GetFile($"{unit}.plist").Exists || await IsLoaded(unit, ct);

    /// <inheritdoc />
    public async Task Retire(string unit, CancellationToken ct = default)
    {
        if (await IsLoaded(unit, ct))
        {
            await Bootout(unit, null, ct);
        }

        // The file too: launchd loads every plist in the directory at the next login, so a unit
        // that was only unloaded would be back after a reboot.
        agents.Directory.GetFile($"{unit}.plist").Delete();
        log.Status($"Retired {unit}.");
    }

    /// <summary>
    /// Whether launchd is running this label.
    /// </summary>
    private Task<bool> IsLoaded(AgentLabel label, CancellationToken ct) => IsLoaded(label.Value, ct);

    private async Task<bool> IsLoaded(string label, CancellationToken ct)
    {
        var result = await commands.Run(Launchctl("list").QuietOutput().ThrowOnError(), ct);
        return result.StandardOutput
            .Split('\n')
            .Any(line => line.Split('\t').LastOrDefault()?.Trim() == label);
    }

    /// <summary>
    /// The domain this process can bootstrap into, asked of the node once. .NET exposes no
    /// getuid, and the generated P/Invoke that would wants unsafe code turned on for the whole
    /// project — a large setting for one number the shell already knows.
    /// </summary>
    private async Task<UserDomain> Domain(CancellationToken ct)
    {
        if (_domain is { } known)
        {
            return known;
        }

        var result = await commands.Run(Command.Create("id").WithArguments("-u").QuietOutput().ThrowOnError(), ct);
        _domain = UserDomain.ForUser(result.StandardOutput);
        return _domain;
    }

    private async Task Bootstrap(IFile file, CancellationToken ct) =>
        await commands.Run(Launchctl("bootstrap", (await Domain(ct)).Value, file.AbsolutePath).ThrowOnError(), ct);

    private async Task Restart(AgentDefinition agent, IFile file, CancellationToken ct)
    {
        var target = (await Domain(ct)).Target(agent.Label);
        if (agent.Restart == AgentRestart.Signal)
        {
            await commands.Run(Launchctl("kill", "SIGTERM", target).ThrowOnError(), ct);
            log.Detail($"Signalled {agent.Label.Value}; it reads the new unit when it next starts.");
            return;
        }

        // A supervisor reads a unit when it loads it, so a changed unit only takes effect
        // across an unload.
        await Bootout(agent.Label.Value, agent.ExitTimeout is { } seconds ? TimeSpan.FromSeconds(seconds) + options.Value.Margin : null, ct);
        await Bootstrap(file, ct);
    }

    /// <summary>
    /// The wait for launchd to let go of a unit, configured under <c>Launchd:Unloading</c>.
    /// </summary>
    internal const string Unloading = "launchd.unloading";

    /// <summary>
    /// Unloads a unit and waits until launchd has let go of it.
    /// </summary>
    /// <remarks>
    /// <c>bootout</c> returns once it has asked the process to stop, not once it has: an agent
    /// that shuts down gracefully — Alloy flushing its queues — is still loaded for a few
    /// seconds, and loading it again meanwhile fails with launchd's bare "Input/output error".
    /// </remarks>
    /// <param name="label">The unit.</param>
    /// <param name="patience">How long this unit may take, when it says; the configured limit otherwise.</param>
    /// <param name="ct">Cancellation token.</param>
    private async Task Bootout(string label, TimeSpan? patience, CancellationToken ct)
    {
        await commands.Run(Launchctl("bootout", $"{(await Domain(ct)).Value}/{label}").ThrowOnError(), ct);
        if (!await pipelines.GetPipeline<bool>(Unloading).Until(async inner => !await IsLoaded(label, inner), patience, ct))
        {
            throw new InvalidOperationException(
                $"{label} was still loaded after it was told to stop; launchd would refuse to load it again.");
        }
    }

    private static Command Launchctl(params string[] arguments) => Command.Create("launchctl").WithArguments(arguments);
}
